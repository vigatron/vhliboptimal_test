void VHBoardInit() {

    MPU_Config();

    /* ВключениеInstruction Cache (I-Cache) */
    SCB_EnableICache();

    /* Включение Data Cache (D-Cache) */
    SCB_EnableDCache();

    /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
    HAL_Init();

    /* Configure the system clock */
    SystemClock_Config();

    /* Initialize all configured peripherals */
    VHSYS_MX_GPIO_Init();

}